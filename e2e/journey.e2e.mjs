  check(!(await win.getByPlaceholder('The system shall…').inputValue()).includes('do not want'), '…and the editor shows it')

  console.log('M5 — compare (pulls first; default = what the last pull brought in)')
  gitIn(pcB, 'pull', '-q')
  const sysName = readdirSync(join(pcB, 'requirements', 'items')).find((f) => readFileSync(join(pcB, 'requirements', 'items', f), 'utf8').includes('title: Temperature accuracy'))
  const sysB = join(pcB, 'requirements', 'items', sysName)
