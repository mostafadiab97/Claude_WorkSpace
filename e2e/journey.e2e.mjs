  // take Bob's version inside ReqMan: undo the unpushed commit, discard the item, pull
  if (!(await changes.isVisible())) await gitbar.getByRole('button', { name: /^Changes/ }).click()
  await changes.getByRole('button', { name: 'Undo last commit “Alice renames the need”' }).click()
