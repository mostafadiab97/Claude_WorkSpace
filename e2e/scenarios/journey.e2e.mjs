  const diff = changesView.getByRole('region', { name: /^Change / })
  await diff.locator('.diff__text').waitFor()
  check((await diff.locator('.diff__src--new').allTextContents()).some((x) => x.includes('A change we do not want')), 'the split difference shows the new text on the right')
  check((await diff.locator('.diff__row', { hasText: 'Priority' }).locator('.diff__cell--new').textContent()).includes('Low'), '…and the field change')
  await shot('10b-split-difference')
  await diff.getByRole('button', { name: 'Take back: Text' }).click()
  await diff.locator('.diff__text').waitFor({ state: 'detached' })
  check(!fileOf('Display readability').includes('A change we do not want') && fileOf('Display readability').includes('priority: Low'), '↶ on the text takes back only the text')
  await changesView.getByRole('button', { name: 'Discard this item’s changes' }).click()
  await changesView.getByRole('button', { name: 'Undo change' }).click()
  await gitbar.locator('.gitbar__notice', { hasText: 'Discarded' }).waitFor()
  check(fileOf('Display readability').includes('priority: High'), 'Discard restores the last committed version')
