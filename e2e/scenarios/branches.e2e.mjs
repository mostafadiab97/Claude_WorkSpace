// 0.12.0 (M8) in the window: the branch panel — create a branch, switch back, compare a branch like a pull request,
// pull it into main, and the question about uncommitted changes when switching.
import { gitIn, gitRepo, launch, scenario } from '../harness.mjs'

await scenario('E2E branches', async (ctx) => {
  const { repo } = gitRepo('branches')
  const t = (ctx.t = await launch({ openPath: repo, prefix: '' }))
  const { win, check } = t

  console.log('A repository with one item, pushed')
  await win.getByRole('button', { name: 'Open repository…' }).click()
  await win.getByRole('button', { name: 'Create requirements folder' }).click()
  await win.locator('.table__empty', { hasText: 'No items yet' }).waitFor()
  await win.getByLabel('New item').selectOption('system-requirement')
  await win.getByPlaceholder('Short name of the requirement').fill('Door lock')
  await win.getByPlaceholder('The system shall…').fill('The door shall lock automatically.')
  await win.getByRole('button', { name: 'Save', exact: true }).click()
  await win.getByRole('button', { name: 'Saved ✓' }).waitFor()
  const gitbar = win.getByRole('region', { name: 'Git' })
  const changesView = win.getByRole('region', { name: 'Changes', exact: true })
  const commitPanel = win.getByRole('complementary', { name: 'Commit' })
  const commit = async (message) => {
    if (!(await changesView.isVisible())) await gitbar.getByRole('button', { name: /^Changes/ }).click()
    await commitPanel.getByLabel('Commit message').fill(message)
    await commitPanel.getByRole('button', { name: /^Commit \d+ changes?$/ }).click()
    await gitbar.locator('.gitbar__notice', { hasText: 'Committed' }).waitFor()
    await changesView.getByRole('button', { name: 'Close changes' }).click()
  }
  await commit('First item')
  await gitbar.getByRole('button', { name: /^Push/ }).click()
  await gitbar.locator('.gitbar__notice', { hasText: 'Pushed' }).waitFor()
  const row = (text) => win.locator('.table__row[data-id]').filter({ hasText: text })

  console.log('Create a branch and work on it')
  const branchButton = gitbar.locator('.gitbar__branch')
  const panel = gitbar.getByRole('dialog', { name: 'Branches' })
  await branchButton.click()
  await panel.waitFor()
  check((await panel.getByRole('list', { name: 'On this PC' }).textContent()).includes('main'), 'the panel lists the branches on this PC')
  await panel.getByLabel('New branch name').fill('feature/door')
  await panel.getByRole('button', { name: 'Create and switch' }).click()
  await gitbar.locator('.gitbar__notice', { hasText: 'Created the branch "feature/door"' }).waitFor()
  check((await branchButton.textContent()).includes('feature/door'), 'the Git bar shows the new branch')
  check(gitIn(repo, 'branch', '--show-current').trim() === 'feature/door', '…and Git is on it')
  await row('Door lock').click()
  await win.getByPlaceholder('Short name of the requirement').fill('Door lock (feature)')
  await win.getByRole('button', { name: 'Save', exact: true }).click()
  await win.getByRole('button', { name: 'Saved ✓' }).waitFor()
  await commit('Feature: rename')
  await t.shot('branches-1-panel')

  console.log('Switch back to main')
  await branchButton.click()
  await panel.locator('.branches__row', { hasText: /^main/ }).getByRole('button', { name: 'Switch' }).click()
  await gitbar.locator('.gitbar__notice', { hasText: 'Switched to "main"' }).waitFor()
  await row('Door lock').waitFor()
  check((await row('Door lock (feature)').count()) === 0, 'the table shows main’s version after the switch')

  console.log('Compare the branch like a pull request, then pull it into main')
  await branchButton.click()
  await panel.locator('.branches__row', { hasText: /^feature\/door/ }).first().getByRole('button', { name: 'Compare' }).click()
  await changesView.waitFor()
  check((await changesView.getByLabel('Show', { exact: true }).inputValue()) === 'branch', 'Changes opens on "what a branch would bring in"')
  await changesView.locator('.compare__row', { hasText: 'Door lock (feature)' }).waitFor()
  check((await changesView.locator('.compare__row').count()) === 1, 'it lists the one item the branch changed')
  await t.shot('branches-2-review')
  await changesView.getByRole('button', { name: 'Close changes' }).click()
  await branchButton.click()
  await panel.locator('.branches__row', { hasText: /^feature\/door/ }).first().getByRole('button', { name: 'Pull into main' }).click()
  await gitbar.locator('.gitbar__notice', { hasText: 'Pulled: 1 item changed' }).waitFor()
  await row('Door lock (feature)').waitFor()
  check(gitIn(repo, 'branch', '--show-current').trim() === 'main', 'pull from branch: main now has the feature’s change')

  console.log('Switching with uncommitted changes asks first')
  await row('Door lock (feature)').click()
  await win.getByPlaceholder('The system shall…').fill('Not committed.')
  await win.getByRole('button', { name: 'Save', exact: true }).click()
  await win.getByRole('button', { name: 'Saved ✓' }).waitFor()
  await branchButton.click()
  await panel.locator('.branches__row', { hasText: /^feature\/door/ }).first().getByRole('button', { name: 'Switch' }).click()
  const ask = panel.getByRole('alertdialog', { name: 'Uncommitted changes' })
  await ask.waitFor()
  check((await ask.textContent()).includes('1 uncommitted change'), 'the question names the uncommitted change')
  check((await ask.getByRole('button').allTextContents()).join('|') === 'Commit first|Take it along|Discard it|Cancel', 'three choices: commit first, take along, discard')
  await t.shot('branches-3-ask')
  await ask.getByRole('button', { name: 'Discard it' }).click()
  await gitbar.locator('.gitbar__notice', { hasText: 'Switched to "feature/door"' }).waitFor()
  check(gitIn(repo, 'status', '--porcelain', '--', 'requirements').trim() === '', 'discard: the change is gone, then the switch')
})
