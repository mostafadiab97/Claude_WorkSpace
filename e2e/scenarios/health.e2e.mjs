// 0.14.0 health tools in the window (P-40, the owner 2 Nov 2026): a feature turned off in Settings disappears from the
// window and comes back when turned on; a team switch in schema.yaml turns it off for the repository and Settings says
// so; "Report a problem" saves one text file with the description, diagnostics and log.
import { appendFileSync, existsSync, readFileSync } from 'node:fs'
import { join } from 'node:path'
import { gitRepo, launch, scenario, temp } from '../harness.mjs'

await scenario('E2E health', async (ctx) => {
  const { repo } = gitRepo('health')
  const t = (ctx.t = await launch({ openPath: repo }))
  const { win, check } = t
  await win.getByRole('button', { name: 'Open repository…' }).click()
  await win.getByRole('button', { name: 'Create requirements folder' }).click()
  await win.locator('.first-run').waitFor()
  // 0.23.0: Import… and Export… live in the "More" menu; with both off the menu button goes too
  const exportBtn = win.getByRole('button', { name: 'More', exact: true })
  const gitbar = win.getByRole('region', { name: 'Git' })
  await gitbar.locator('.gitbar__branch').waitFor()
  check((await exportBtn.count()) === 1, 'Export is there at first')

  console.log('Keyboard shortcuts (0.15, UX-25)')
  await win.locator('.table').click()
  await win.keyboard.press('Control+f')
  check(await win.locator('.toolbar__search').evaluate((el) => el === document.activeElement), 'Ctrl+F goes to the search box')
  await win.keyboard.press('Control+Shift+C')
  await win.getByRole('button', { name: /^Changes/, pressed: true }).waitFor()
  check(true, 'Ctrl+Shift+C opens Changes')
  await win.keyboard.press('Control+Shift+C')
  await win.keyboard.press('Control+/')
  await win.getByRole('heading', { name: '18. Keyboard shortcuts' }).waitFor()
  check(true, 'Ctrl+/ opens the keyboard shortcuts page')
  await win.getByRole('button', { name: 'Back', exact: true }).click()

  console.log('A "nothing to do" message is blue, not red (0.14.1)')
  await gitbar.getByRole('button', { name: /^Push/ }).click()
  const note = gitbar.locator('.gitbar__notice', { hasText: 'Nothing to push yet' })
  await note.waitFor()
  check(await note.evaluate((el) => el.classList.contains('gitbar__notice--info')), '"Nothing to push yet" is shown as a neutral (blue) note')
  await t.shot('health-0-note-light')

  console.log('Turn Export off on this PC')
  await win.getByRole('button', { name: 'Settings and diagnostics' }).click()
  const nav = win.getByRole('navigation', { name: 'Settings and help' })
  await nav.getByRole('button', { name: 'Environment' }).click()
  const features = win.getByRole('region', { name: 'Features' })
  await features.getByRole('checkbox', { name: /^Export/ }).uncheck()
  await t.shot('health-1-settings')
  await win.getByRole('button', { name: 'Back', exact: true }).click()
  await win.locator('.first-run').waitFor()
  await exportBtn.click()
  check((await win.getByRole('menuitem', { name: 'Export…' }).count()) === 0, 'Export is gone from the toolbar')
  check((await win.getByRole('menuitem', { name: 'Import…' }).count()) === 1, '…the other features stay')
  await win.keyboard.press('Escape')
  await win.getByRole('button', { name: 'Settings and diagnostics' }).click()
  await nav.getByRole('button', { name: 'Environment' }).click()
  await features.getByRole('checkbox', { name: /^Export/ }).check()
  await win.getByRole('button', { name: 'Back', exact: true }).click()
  await exportBtn.waitFor()
  check(true, 'turned on again, Export is back')

  console.log('The team turns Branches off in schema.yaml')
  appendFileSync(join(repo, 'requirements', '.reqochet', 'schema.yaml'), '\nfeatures:\n  branches: false\n')
  await win.getByRole('button', { name: 'Close repository' }).click()
  await win.getByRole('button', { name: 'Open repository…' }).click()
  await win.locator('.first-run').waitFor()
  await gitbar.locator('.gitbar__branch').waitFor()
  check(await gitbar.locator('.gitbar__branch').isDisabled(), 'the branch button no longer opens the branch panel')
  await win.getByRole('button', { name: 'Settings and diagnostics' }).click()
  await nav.getByRole('button', { name: 'Environment' }).click()
  check((await features.textContent()).includes('Turned off for this repository by the team'), 'Settings says the team turned it off')
  // the owner, 14 Nov 2026: Features, Environment and Versions are one page now
  check((await win.getByRole('region', { name: 'Versions' }).count()) === 1, 'Environment, Versions and Features share one page')
  await nav.getByRole('button', { name: 'Appearance' }).click()
  await win.getByRole('region', { name: 'Theme editor' }).waitFor()
  check((await win.getByRole('region', { name: 'Theme editor' }).count()) === 1 && (await win.getByRole('region', { name: 'Versions' }).count()) === 0, 'the Appearance page holds the theme editor, not the Versions card')
  await nav.getByRole('button', { name: 'Diagnostics' }).click()
  check((await win.getByRole('button', { name: /Run release self-test|Run self-test/ }).count()) >= 1, 'the self-tests are on the problems page')
  // Settings → Privacy and access (the owner, 8 Nov 2026)
  await nav.getByRole('button', { name: 'Privacy and access' }).click()
  const privacy = win.getByRole('region', { name: 'Privacy and access' })
  await privacy.waitFor()
  check((await privacy.getByRole('heading').count()) === 5 && (await privacy.getByText(/never sees your password/).count()) === 1, 'the Privacy page lists what the app reads, keeps, sends and may change')
  await t.shot('health-privacy')
  await nav.getByRole('button', { name: 'Environment' }).click()
  await t.shot('health-4-env')

  check((await win.getByRole('region', { name: 'Versions' }).getByRole('button', { name: 'Go back to an earlier version…' }).count()) === 1, 'Settings has Versions → go back to an earlier version')

  console.log('Settings and help: the user guide, one page per section (0.14.2, 0.14.3)')
  check((await nav.getByRole('button', { name: '1. Quick start (15 minutes)' }).count()) === 0, 'the guide topics are folded at first (0.14.5)')
  await nav.getByRole('button', { name: /User guide/ }).click()
  await nav.getByRole('button', { name: '1. Quick start (15 minutes)' }).click()
  const guide = win.getByRole('article', { name: 'User guide' })
  await guide.getByRole('heading', { name: '1. Quick start (15 minutes)' }).waitFor()
  check((await guide.getByRole('heading', { name: '2. Ideas you need to know' }).count()) === 0, 'the quick start is a page of its own')
  // pictures in the guide (the owner, 8 Nov 2026)
  await nav.getByRole('button', { name: '2. Ideas you need to know' }).click()
  await guide.locator('figure.guide-figure svg').first().waitFor()
  check((await guide.getByRole('img', { name: /Where your requirements live/ }).count()) === 1, 'the guide shows a picture of where requirements live')
  await t.shot('health-guide-figure')
  // the owner, 0.15.0 step 4: Back stays visible when the left panel is scrolled down
  await win.setViewportSize({ width: 1280, height: 560 })
  await win.locator('.settings-nav').evaluate((el) => el.scrollTo(0, el.scrollHeight))
  const back = await win.locator('.settings-nav__back').boundingBox()
  const navBox = await win.locator('.settings-nav').boundingBox()
  check(back !== null && navBox !== null && back.y >= navBox.y - 1 && back.y < navBox.y + 60, 'Back stays at the top of the scrolled left panel')
  const covered = await win.evaluate(() => {
    const bar = document.querySelector('.settings-nav__top')?.getBoundingClientRect()
    if (!bar) return false
    const at = document.elementFromPoint(bar.left + 4, bar.bottom - 3)
    return at !== null && at.closest('.settings-nav__top') !== null
  })
  check(covered, '…on a bar of its own: the entries scroll under it, not around the button (0.15.1 step 4)')
  await win.setViewportSize({ width: 1400, height: 860 })
  await nav.getByRole('button', { name: 'Introduction and contents' }).click()
  await guide.getByRole('link', { name: 'Import and export (Excel, ReqIF, CSV, Markdown)' }).click()
  await guide.getByRole('heading', { name: '11. Import and export' }).waitFor()
  check((await guide.getByRole('heading', { name: '11. Import and export' }).count()) === 1, "a link in the contents opens that section's page")
  await t.shot('health-3-guide')
  await nav.getByRole('button', { name: 'Diagnostics' }).click()

  console.log('Report a problem')
  const file = join(temp('health-report'), 'report.txt')
  await t.saveAs(file)
  const report = win.getByRole('region', { name: 'Report a problem' })
  await report.getByLabel('What happened?').fill('The branch button does nothing.')
  await report.getByRole('button', { name: 'Save report…' }).click()
  await report.getByText(/Report saved/).waitFor()
  const text = existsSync(file) ? readFileSync(file, 'utf8') : ''
  check(text.includes('The branch button does nothing.'), 'the report holds the description')
  check(/reqochet \d+\.\d+\.\d+/.test(text) && text.includes('Git:'), '…the diagnostics')
  check(text.includes('== Log (last'), '…and the end of the log')
  check((await report.getByLabel('What happened?').inputValue()) === '', 'the text box is empty again after saving (the owner on 0.14.0 step 3)')
  await t.shot('health-2-report')
})
