  const stop = gitbar.locator('.gitbar__notice--error', { hasText: 'Pull stopped' })
  await stop.waitFor()
  check((await stop.locator('.gitbar__items').textContent()).includes(stkName.replace('.md', '')), 'conflict: pull stops and names the item changed on both sides')
  check(gitIn(repo, 'rev-parse', 'HEAD') === headBefore && gitIn(repo, 'status', '--porcelain', '--', 'requirements') === '', '…and nothing was changed')
  await shot('12-pull-stopped')
  await gitbar.getByRole('button', { name: /^Push/ }).click()
