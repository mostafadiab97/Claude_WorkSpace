// 1a (0.17.0) — documents as folders (S-10), item/link types in the window (S-04), required fields (S-05), drag and
// drop in the Columns menu (S-11). A project made before 0.17 (requirements/items) is offered a real document name.
import { copyFileSync, existsSync, mkdirSync, readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { documentAction, gitIn, gitRepo, launch, pickDocument, root, scenario } from '../harness.mjs'

await scenario('E2E structure-0.17', async (ctx) => {
  const { repo } = gitRepo('struct017')
  const req = join(repo, 'requirements')
  mkdirSync(join(req, '.reqochet'), { recursive: true })
  mkdirSync(join(req, 'items'), { recursive: true })
  copyFileSync(join(root, 'config', 'default-schema.yaml'), join(req, '.reqochet', 'schema.yaml'))
  writeFileSync(join(req, 'items', 'REQ-AAAAAAA.md'), '---\nid: REQ-AAAAAAA\ntype: system-requirement\ntitle: Old one\norder: a0\n---\nx\n')
  gitIn(repo, 'add', '-A')
  gitIn(repo, 'commit', '-q', '-m', 'made before 0.17')

  const t = (ctx.t = await launch({ openPath: repo }))
  const { win, check } = t
  await win.getByRole('button', { name: 'Open repository…' }).click()
  await win.locator('.table__row', { hasText: 'Old one' }).waitFor()

  console.log('S-10 — a project made before 0.17 names its document')
  const offer = win.locator('.document-notice')
  check((await offer.count()) === 1, 'the "items" folder is offered a real name')
  await offer.getByRole('button', { name: 'Name the document' }).click()
  await win.getByLabel(/New name for items/).fill('System')
  await win.getByRole('button', { name: 'Rename', exact: true }).click()
  await win.locator('.doc-btn__name', { hasText: /^System$/ }).waitFor({ timeout: 15_000 })
  check(existsSync(join(req, 'System', 'REQ-AAAAAAA.md')) && !existsSync(join(req, 'items')), 'the folder is renamed to System')
  check(gitIn(repo, 'log', '-1', '--format=%s').includes('Rename the document items to System'), 'one commit records the rename')
  await t.shot('structure-0.17-documents')

  console.log('S-10 — a second document, its own tree and numbers')
  await documentAction(win, 'New document')
  await win.getByLabel('Name of the new document').fill('Software')
  await win.getByRole('button', { name: 'Create', exact: true }).click()
  await win.locator('.doc-btn__name', { hasText: /^Software$/ }).waitFor()
  check((await win.locator('.doc-btn__count').textContent())?.trim() === '0', 'the new document is shown')
  await win.locator('.first-run').getByRole('button', { name: 'Add the first requirement' }).click()
  await win.getByPlaceholder('Short name of the requirement').fill('Software one')
  await win.keyboard.press('Control+s')
  await win.locator('.table__row', { hasText: 'Software one' }).waitFor()
  const swFiles = readdirSync(join(req, 'Software')).filter((f) => f.endsWith('.md'))
  check(swFiles.length === 1, `the new item's file is in requirements/Software (${swFiles.length})`)
  check((await win.locator('.table__row', { hasText: 'Old one' }).count()) === 0, 'the Software document shows only its own items')
  const num = await win.locator('.table__row', { hasText: 'Software one' }).locator('.table__td--number').textContent()
  check((num ?? '').trim() === '1', `numbers restart in each document (${num})`)
  await pickDocument(win, 'All documents (2)')
  await win.locator('.table__row', { hasText: 'Old one' }).waitFor()
  await win.locator('.table__row', { hasText: 'Software one' }).waitFor()
  check((await win.locator('.table__row--group').count()) === 2 && (await win.locator('.table__row[data-id]').count()) === 2, 'All documents shows both, one group per document')
  // a group closes and opens (the owner, 8 Nov 2026)
  await win.locator('.table__row--group', { hasText: 'Software' }).getByRole('button').click()
  await win.locator('.table__row', { hasText: 'Software one' }).waitFor({ state: 'detached' })
  check((await win.locator('.table__row', { hasText: 'Old one' }).count()) === 1, 'closing one document group hides only its items')
  await win.locator('.table__row--group', { hasText: 'Software' }).getByRole('button').click()
  await win.locator('.table__row', { hasText: 'Software one' }).waitFor()
  await t.shot('structure-0.17-groups')

  console.log('owner 8 Nov — drag a column header to a new place')
  const heads = async () => (await win.locator('.table__head [role="columnheader"]').evaluateAll((els) => els.map((e) => e.getAttribute('data-column'))))
  const before = await heads()
  // the third column (first movable after No. and Title) and the next one swap places
  const [first, second] = before.filter((k) => k !== 'number' && k !== 'title')
  await win.locator(`.table__head [data-column="${second}"]`).dragTo(win.locator(`.table__head [data-column="${first}"]`))
  await win.waitForTimeout(300)
  const after = await heads()
  check(after.indexOf(second) < after.indexOf(first) && after.indexOf(second) > after.indexOf('title'), `a column header dragged left lands before the other (${before.join(',')} → ${after.join(',')})`)

  console.log('S-04 / S-05 — types in the window, a required field, the Incomplete filter')
  await win.getByRole('button', { name: 'View', exact: true }).click()
  await win.getByRole('button', { name: 'Edit types…' }).click()
  const dlg = win.getByRole('dialog', { name: 'Item and link types' })
  await dlg.waitFor()
  const sysRow = dlg.locator('.fields-table__row').filter({ has: win.locator('input[value="System Requirement"]') })
  check((await sysRow.getByText(/1 item/).count()) === 1, 'the window shows how many items use a type (Old one)')
  check(await sysRow.getByRole('button', { name: 'Remove' }).isDisabled(), 'a used type cannot be removed')
  await sysRow.locator('summary').click()
  await sysRow.getByLabel('Priority').check()
  await dlg.getByRole('button', { name: 'Save', exact: true }).click()
  await dlg.waitFor({ state: 'detached' })
  await win.getByRole('button', { name: /^Filters/ }).click()
  await win.getByLabel('Links').selectOption('incomplete').catch(async () => win.locator('select').filter({ hasText: 'Incomplete' }).selectOption('incomplete'))
  await win.waitForTimeout(500)
  const rowsNow = await win.locator('.table__row').allTextContents()
  check(rowsNow.length === 1 && rowsNow[0].includes('Old one'), `the system requirement without the now required Priority is listed as incomplete (${rowsNow.length})`)
  await t.shot('structure-0.17-incomplete')
  await win.keyboard.press('Escape')
})
