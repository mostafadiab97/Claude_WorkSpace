  await changes.getByLabel('Commit message').fill('Alice renames the need')
  await changes.getByRole('button', { name: /^Commit 1 change$/ }).click()
  await gitbar.locator('.gitbar__notice', { hasText: 'Committed' }).waitFor()
  const headBefore = gitIn(repo, 'rev-parse', 'HEAD')
