  await decide.getByRole('button', { name: 'Finish the pull' }).click()
  await gitbar.locator('.gitbar__notice', { hasText: '1 decided by you' }).waitFor()
  await rowOf('Comfortable temperature (Bob)').waitFor()
  check(gitIn(repo, 'log', '-1', '--format=%s').trim() === 'Merge origin/main into main', 'the decision becomes a merge commit')
  await gitbar.getByRole('button', { name: /^Push/ }).click()
  await offer.getByRole('button', { name: 'Push without pulling' }).click()
  await gitbar.locator('.gitbar__notice', { hasText: 'Pushed' }).waitFor()
  check(true, 'after the decision, Bob’s title is used and the merge is pushed')

  // take back one part of an uncommitted edit (O-05), then discard the rest
  await rowOf('Display readability').click()
  await win.getByPlaceholder('The system shall…').fill('A change we do not want')
